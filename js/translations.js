function getCurrentLanguage() {
  return (window.APP_STATE && window.APP_STATE.currentLang) || 'nl';
}

function t(key, vars = {}, lang = getCurrentLanguage()) {
  let str = (I18N[lang] && I18N[lang][key]) || (I18N.en && I18N.en[key]) || key;
  Object.entries(vars).forEach(([k, v]) => {
    str = str.replaceAll(`{${k}}`, v);
  });
  return str;
}

function getCriteriaLabel(key, lang = getCurrentLanguage()) {
  return CRITERIA_META[key]?.[lang]?.label || key;
}

function getCriteriaDesc(key, lang = getCurrentLanguage()) {
  return CRITERIA_META[key]?.[lang]?.desc || '';
}

function localizePlaceType(key, lang = getCurrentLanguage()) {
  return PLACE_TYPE_META[key]?.[lang] || key;
}

function localizeFamiliarity(key, lang = getCurrentLanguage()) {
  return FAMILIARITY_META[key]?.[lang] || key;
}

function tagLabel(key, lang = getCurrentLanguage()) {
  return TAG_META[key]?.[lang] || key;
}
